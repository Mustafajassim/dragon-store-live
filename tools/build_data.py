#!/usr/bin/env python3
"""Validate the JSON data files and regenerate data/data.fallback.js.

Run after every edit of data/store.json or data/products.json:
    python tools/build_data.py

data/data.fallback.js is only used when the site is opened straight from disk
(file://), where browsers block fetch(). Normal hosting never loads it.
Standard library only.
"""
import json, os, sys, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def load(name):
    with open(os.path.join(ROOT, 'data', name), encoding='utf-8') as f:
        return json.load(f)

store, doc = load('store.json'), load('products.json')
products = doc['products']
errors = []

cat_ids = {c['id'] for c in store['categories']}
real_cat_ids = {c['id'] for c in store['categories'] if not c.get('shared') and not c.get('comingSoon')}

ids = collections.Counter(p['id'] for p in products)
errors += [f'duplicate product id: {i}' for i, n in ids.items() if n > 1]
nums = collections.Counter(p['productNumber'] for p in products if p.get('productNumber') is not None)
errors += [f'duplicate productNumber: {i}' for i, n in nums.items() if n > 1]
slugs = collections.Counter((p['categoryId'], p['slug']) for p in products)
errors += [f'duplicate slug in category: {k}' for k, n in slugs.items() if n > 1]

for p in products:
    pid = p['id']
    if p['categoryId'] not in cat_ids: errors.append(f'{pid}: unknown categoryId {p["categoryId"]}')
    if p['categoryId'] in real_cat_ids and not p.get('comingSoon'):
        if not isinstance(p.get('price'), int) or p['price'] <= 0: errors.append(f'{pid}: price must be a positive integer')
        if not isinstance(p.get('weightGrams'), int): errors.append(f'{pid}: weightGrams must be an integer')
        if not p.get('productNumber'): errors.append(f'{pid}: missing productNumber')
    if not p.get('images'): errors.append(f'{pid}: no images')
    for img in p.get('images', []):
        if not os.path.isfile(os.path.join(ROOT, store.get('assetBase', '') + img)): errors.append(f'{pid}: missing file {img}')

for s in store['hero']['slides']:
    if not os.path.isfile(os.path.join(ROOT, s['image'])): errors.append(f'hero: missing file {s["image"]}')
if not os.path.isfile(os.path.join(ROOT, store['brand']['logo'])): errors.append('brand logo missing')
for c in store['collections']:
    if c['id'] not in cat_ids: errors.append(f'collection {c["id"]} has no matching category')

if errors:
    print('✗ validation failed:'); [print('  -', e) for e in errors]; sys.exit(1)

with open(os.path.join(ROOT, 'data', 'data.fallback.js'), 'w', encoding='utf-8') as f:
    f.write('/* AUTO-GENERATED by tools/build_data.py — do not edit. Used only for file:// previews. */\n')
    f.write('window.__DRAGON_DATA__=' + json.dumps({'store': store, 'products': doc}, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(f'✓ {len(products)} products, {len(store["categories"])} categories — data valid, data/data.fallback.js regenerated')
