/* DATA LAYER
   fetchData()    – loads data/store.json + data/products.json
   buildCatalog() – turns product records into the runtime catalogue
                    (adds the shared sections: trending / best-sellers / discounts, and IoT placeholders)
   assetUrl()     – resolves an asset path stored in the JSON files
   Nothing in here touches the DOM, so it is easy to test or swap for a real API later. */

const DATA_URLS={store:'data/store.json',products:'data/products.json',fallback:'data/data.fallback.js'};
let ASSET_BASE='';

function assetUrl(path){return path?ASSET_BASE+path:path;}

function shuffleArray(arr){const c=[...arr];for(let i=c.length-1;i>0;i--){const j=Math.floor(Math.random()*(i+1));[c[i],c[j]]=[c[j],c[i]];}return c;}

function fetchJSON(url){
  return fetch(url,{cache:'no-cache'}).then(r=>{
    if(!r.ok)throw new Error(url+' → HTTP '+r.status);
    return r.json();
  });
}

function loadScript(src){
  return new Promise((resolve,reject)=>{
    const s=document.createElement('script');
    s.src=src;s.onload=resolve;s.onerror=()=>reject(new Error('Cannot load '+src));
    document.head.appendChild(s);
  });
}

async function fetchData(){
  let store,doc;
  try{
    [store,doc]=await Promise.all([fetchJSON(DATA_URLS.store),fetchJSON(DATA_URLS.products)]);
  }catch(err){
    // Browsers block fetch() for local files (file://). Only in that case use the
    // pre-bundled copy of the same JSON (generated by tools/build_data.py).
    if(location.protocol!=='file:')throw err;
    await loadScript(DATA_URLS.fallback);
    if(!window.__DRAGON_DATA__)throw err;
    store=window.__DRAGON_DATA__.store;
    doc=window.__DRAGON_DATA__.products;
  }
  ASSET_BASE=store.assetBase||'';
  return{store,products:doc.products};
}

function buildCatalog(store,records){
  const cats=store.categories;
  const realCats=cats.filter(c=>!c.shared&&!c.comingSoon);
  const fallbackImages=(store.fallbackImages.product||[]).map(assetUrl);
  const all=[];

  // 1) real catalogue sections (own products)
  realCats.forEach(cat=>{
    records.filter(r=>r.categoryId===cat.id).forEach(r=>{
      const images=r.images&&r.images.length?r.images.map(assetUrl):fallbackImages;
      if(r.price==null||!r.weightGrams){
        all.push({id:r.id,categoryId:cat.id,categoryName:cat.name,name:r.name,comingSoon:true,price:null,priceLabel:r.priceLabel||store.labels.priceTbd,images,productNumber:r.productNumber});
        return;
      }
      all.push({id:r.id,categoryId:cat.id,categoryName:cat.name,name:r.name,price:r.price,weightGrams:r.weightGrams,images,material:r.material,weight:`${r.weightGrams}g`,productNumber:r.productNumber});
    });
  });

  // 2) shared sections, driven by store.collections
  const strategies={
    'random-per-category':col=>realCats.flatMap(cat=>shuffleArray(all.filter(p=>p.categoryId===cat.id)).slice(0,col.perCategory)),
    'slice-per-category':col=>realCats.flatMap(cat=>all.filter(p=>p.categoryId===cat.id).slice(col.offset,col.offset+col.count)),
    'min-weight':col=>all.filter(p=>realCats.some(c=>c.id===p.categoryId)&&p.weightGrams>=col.minWeightGrams)
  };
  store.collections.forEach(col=>{
    const def=cats.find(c=>c.id===col.id);
    const pick=strategies[col.strategy];
    if(!def||!pick)return;
    pick(col).forEach(p=>all.push({...p,id:`${col.id}-${p.id}`,categoryId:col.id,categoryName:def.name,originCategoryId:p.categoryId}));
  });

  // 3) "coming soon" sections (IoT): no price, details or buy button
  cats.filter(c=>c.comingSoon).forEach(cat=>{
    records.filter(r=>r.categoryId===cat.id).forEach(r=>{
      const images=r.images&&r.images.length?r.images.map(assetUrl):[assetUrl(store.fallbackImages.comingSoon)];
      all.push({id:r.id,categoryId:cat.id,categoryName:cat.name,name:r.name,comingSoon:true,price:null,images});
    });
  });

  return all;
}
